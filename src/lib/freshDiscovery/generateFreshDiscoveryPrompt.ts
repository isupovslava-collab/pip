import { labels } from '../../data/dictionaries.ts'
import type { ContentTypeId, SearchQuery } from '../../types/reference.ts'

export const freshDiscoveryGuidance: Record<ContentTypeId, string[]> = {
  kpi: ['сильная иерархия главной метрики', 'plan/fact или цель/факт', 'executive KPI', 'тренд с ясным выводом'],
  comparison: ['альтернативы по единым критериям', 'pricing или option comparison', 'видимая рекомендация', 'обоснование выбора'],
  timeline: ['roadmap', 'milestones', 'этапы реализации', 'сроки, статусы и зависимости'],
  process: ['ясная последовательность', 'algorithm или workflow', 'решения и переходы между шагами', 'видимый итог процесса'],
  dashboard: ['несколько связанных метрик', 'status и trend', 'отклонения от цели', 'управленческий вывод'],
  cover: ['сильный opening visual', 'keynote или executive cover', 'минималистичная либо editorial title treatment', 'чёткая тема без мелкого текста'],
  story: ['тезис и визуальный аргумент', 'before/after', 'narrative structure', 'доказательство и запоминающийся вывод'],
  table: ['executive table', 'matrix или structured comparison', 'читабельная screen-first таблица', 'видимая иерархия строк, столбцов и вывода'],
}

export function generateFreshDiscoveryPrompt(query: SearchQuery): string {
  const guidance = freshDiscoveryGuidance[query.contentTypeId].map((item) => `— ${item}`).join('\n')
  return `Найди в интернете современные и свежие профессиональные референсы конкретных презентационных слайдов для следующей задачи.

Контекст:
— Сценарий: ${labels.scenario[query.scenarioId]}
— Аудитория: ${labels.persona[query.personaId]}
— Цель: ${labels.goal[query.goalId]}
— Стиль: ${labels.style[query.styleId]}
— Тип слайда: ${labels.contentType[query.contentTypeId]}

Для выбранного типа слайда особенно ищи:
${guidance}

Найди 6–10 действительно сильных визуальных примеров.

Приоритет:
1. Современные источники, желательно последних 3–4 лет, но допускаются более старые примеры, если дизайн всё ещё выглядит актуально.
2. Реальные презентации, investor decks, strategy decks, annual reports, consulting reports, keynote slides, публичные корпоративные или институциональные материалы.
3. Конкретная презентация + конкретная страница/слайд.
4. Официальный первоисточник предпочтительнее агрегатора.
5. Слайд должен быть пригоден именно как презентационный дизайн-референс для экрана, а не просто как страница текстового PDF или отчёта.
6. Визуальное качество и способность вдохновить важнее формального совпадения по теме.

Для каждого результата укажи:
— организация;
— название документа/презентации;
— конкретный слайд или страницу;
— прямую ссылку;
— год;
— почему этот visual подходит под мою задачу;
— какой композиционный принцип можно использовать;
— насколько дизайн выглядит современно;
— является ли ссылка первоисточником.

Критически важно:
— не придумывай URL;
— не придумывай номера страниц;
— не придумывай названия слайда;
— если конкретную страницу проверить не удалось, прямо напиши это;
— не выдавай template/aggregator за официальный первоисточник;
— не включай слабые wireframes и обычные стандартные диаграммы только ради количества.`
}
