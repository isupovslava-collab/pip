import { labels } from '../../data/dictionaries.ts'
import type { ContentTypeId, SearchQuery } from '../../types/reference.ts'

export const FRESH_DISCOVERY_PROMPT_VERSION = 'v2' as const

export const freshDiscoveryGuidance: Record<ContentTypeId, string[]> = {
  kpi: ['executive KPI slides', 'plan/fact', 'крупные ключевые метрики', 'динамику + управленческий вывод', '3–6 KPI с сильной визуальной иерархией'],
  comparison: ['option comparison', 'alternatives', 'pricing / package comparison', 'criteria matrix', 'recommended option', 'визуально понятное сравнение 2–4 вариантов'],
  timeline: ['roadmap', 'milestones', 'этапы реализации', 'сроки, статусы и зависимости', 'phased execution', 'achieved vs expected milestones'],
  process: ['process', 'workflow', 'algorithm', 'sequence of actions', 'decision flow', '3–7 понятных этапов'],
  dashboard: ['executive dashboard', 'multiple metrics', 'status / trends', 'deviations', 'plan/fact', 'компактную управленческую сводку'],
  cover: ['keynote cover', 'executive title slide', 'сильный opening visual', 'минималистичный или editorial title treatment', 'современную крупную типографику'],
  story: ['strong thesis', 'visual argument', 'before/after', 'problem → insight → conclusion', 'storytelling slide', 'один сильный визуальный тезис'],
  table: ['executive table', 'matrix', 'structured comparison', 'status table', 'decision table', 'screen-first таблицу, читаемую без zoom'],
}

export function generateFreshDiscoveryPrompt(query: SearchQuery): string {
  const guidance = freshDiscoveryGuidance[query.contentTypeId].map((item) => `— ${item};`).join('\n')
  return `Найди в интернете современные и свежие профессиональные референсы конкретных презентационных слайдов для следующей задачи.

Контекст:
— Сценарий: ${labels.scenario[query.scenarioId]}
— Аудитория: ${labels.persona[query.personaId]}
— Цель: ${labels.goal[query.goalId]}
— Стиль: ${labels.style[query.styleId]}
— Тип слайда: ${labels.contentType[query.contentTypeId]}

Для выбранного типа особенно ищи:
${guidance}

Найди до 8 действительно сильных визуальных примеров.

Если удалось подтвердить только 4–6 сильных вариантов — покажи только их.
Не добавляй слабые примеры ради количества.

Главные критерии отбора:

1. Design Freshness: предпочтительны материалы последних 3–4 лет. Более старые допускаются только тогда, когда визуальный язык всё ещё выглядит современно.

2. Ищи реальные презентационные материалы: investor decks, strategy decks, consulting presentations, keynote slides, публичные корпоративные и институциональные презентации.

3. Annual report или аналитический PDF используй только тогда, когда конкретная страница действительно выглядит как сильный экранный презентационный слайд.

4. Для каждого результата обязательно найди конкретную презентацию и конкретный слайд или страницу.

5. Перед включением результата визуально проверь сам конкретный слайд. Не включай его только потому, что название документа или страницы подходит по теме.

6. Официальный первоисточник предпочтительнее агрегатора.

7. Визуальное качество и способность вдохновить важнее формального совпадения ключевых слов.

Screen Suitability — обязательный фильтр: слайд должен нормально восприниматься на экране без увеличения, иметь ясную визуальную иерархию и выглядеть как законченный профессиональный presentation reference.

Исключай:
— страницы годовых и аналитических отчётов, похожие на журнальный разворот или буклет;
— страницы с большим количеством мелкого текста;
— обычные таблицы и стандартные графики без сильной визуальной идеи;
— слишком простые схемы и wireframes;
— визуально устаревшие слайды;
— варианты, которые невозможно нормально воспринимать на экране без увеличения.

Главный тест: пример должен выглядеть так, чтобы пользователь захотел использовать его как визуальный ориентир для собственного презентационного слайда.

Раздели результаты на:

A. Exact References
— прямо соответствуют выбранному типу слайда.

B. Creative Alternatives
— решают ту же коммуникационную задачу необычным визуальным способом.

Сначала показывай Exact References. Creative Alternatives — только после них и только если они действительно полезны.

Расположи варианты от самого сильного визуального решения к более слабым.

Для каждого результата укажи:
— организацию;
— название презентации или документа;
— конкретный слайд или страницу;
— год;
— прямую ссылку;
— почему подходит под мою задачу;
— какой композиционный принцип можно использовать;
— насколько дизайн выглядит современно;
— является ли ссылка первоисточником.

Если интерфейс позволяет — покажи preview найденного слайда.

Критически важно:
— не придумывай URL;
— не придумывай номер страницы;
— не придумывай название или содержание слайда;
— если конкретную страницу визуально проверить не удалось, не включай её в основной список;
— не выдавай template или aggregator за официальный первоисточник.`
}
